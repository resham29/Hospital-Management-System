#what is sessionlocal and how does it work in sqlalchemy
#SessionLocal: A factory class generated by sessionmaker(). Statically configures database behaviors once and serves as a generator for session instances.

#Session: An individual workspace instance created by calling SessionLocal(). Manages a single database connection/transaction for a short-lived operation or web request.

def get_db():
    db = SessionLocal()
    try:
        #yield keyword in python: The yield keyword in Python is used to transform a standard function into a generator function
        yield db
    finally:
        db.close()

# CREATE PATIENT
@router.post("/patient")
def create_patient(
    patient: PatientCreate,
    #Depends is a function in which we can call another function which we are dependant on.
    db: Session = Depends(get_db) #what does depend do in fastapi and what is session in sqlalchemy
):
    #Check if patient already exists
    #what is .filter() method in sqlalchemy and how does it work
    #.filter() method in SQLAlchemy is a core ORM tool used to restrict the rows returned by a database query.
    existing_patient = db.query(Patient).filter( 
        Patient.patEmail == patient.patEmail
    ).first()
    #.first() method is used to execute a query and retrieve only the very first row of the result set

#status code for read, write, update, delete operations in REST API 
#status code for errors
    if existing_patient:
        raise HTTPException(
            status_code=409,
            detail="Patient already exists"
        )
    new_patient = Patient(
        patName=patient.patName,
        patAge=patient.patAge,
        patPhone=patient.patPhone,
        patEmail=patient.patEmail
    )
    #print(new_patient) and check what do we get when we print new_patient
    db.add(new_patient)
    db.commit()
    db.refresh(new_patient)

    return new_patient

