# GET PATIENT BY ID
@router.get("/patient/{patId}") #{patId} is a path parameter
def get_patient(patId: int, db: Session = Depends(get_db)):

    patient = db.query(Patient).filter(
        Patient.id == patId
    ).first()

    if not patient:
        raise HTTPException(
            status_code=404,
            detail="Patient not found"
        )
    #db.query() is the legacy method for executing SELECT statements in SQLAlchemy
    appointments = db.query(Appointment).filter(
        Appointment.patId == patId
    ).all()

    appointment_history = []
    
    for appointment in appointments:

        doctor = db.query(Doctor).filter(
            Doctor.id == appointment.docId
        ).first()

        department = db.query(Department).filter(
            Department.id == doctor.deptId
        ).first()

        reports = db.query(PatientReport).filter(
            PatientReport.appointment_id == appointment.id
        ).all()
        
        report_history = []
        
        for report in reports:
            report_history.append({
                "reportId": report.id,
                "filename": report.filename,
                "file_path": report.file_path,
                "report_type": report.report_type
            })

        appointment_history.append({
            "appointmentId": appointment.id,
            "doctorId": appointment.docId,
            "doctorName": doctor.docName,
            "departmentName": department.deptName,
            "problem": appointment.problem,
            "fees": appointment.fees,
            "resolutionStatus": appointment.resolutionStatus,
            "report": report_history
        })

    return {
        "id": patient.id,
        "patName": patient.patName,
        "patAge": patient.patAge,
        "patPhone": patient.patPhone,
        "patEmail": patient.patEmail,
        "appointments": appointment_history
    }

@router.post("/patient/{patId}/upload")
async def get_patient(patId: int, appointmentId: int, file: UploadFile = File(...), db: Session = Depends(get_db)):
    patient = db.query(Patient).filter(
        Patient.id == patId
    ).first()

    if not patient:
        raise HTTPException(status_code=404, detail="Patient not found")

    appointment = db.query(Appointment).filter(
        Appointment.id == appointmentId,
        Appointment.patId == patId
    ).first()

    if not appointment:
        raise HTTPException(
            status_code=404,
            detail="Appointment not found for this patient"
        )
    
    file_path = await upload_image(file)
    print("file:", file_path)

    report = PatientReport(
        patient_id=patId,
        appointment_id=appointmentId,
        filename=file.filename,
        file_path=file_path,
        report_type="Prescription"
    )

    db.add(report)
    db.commit()
    db.refresh(report)

    return JSONResponse(
        content={
            "message": "File uploaded successfully",
            "patientId": patId,
            "appointmentId": appointmentId,
            "filename": file.filename,
            "content-type": file.content_type,
            "file_path": file_path
        }
    )
    
#UPDATE PATIENT
@router.put("/patient/{patId}")
def update_patient(
    patId: int,
    patient: PatientCreate,
    db: Session = Depends(get_db)
):
    existing_patient = db.query(Patient).filter(Patient.id == patId).first()

    if not existing_patient:
        raise HTTPException(
            status_code=404,
            detail="Patient not found"
        )

    existing_patient.patName = patient.patName
    existing_patient.patAge = patient.patAge
    existing_patient.patPhone = patient.patPhone
    existing_patient.patEmail = patient.patEmail

    db.commit()
    db.refresh(existing_patient)

    return existing_patient

# DELETE PATIENT
@router.delete("/patient/{patId}")
def delete_patient(
    patId: int,
    db: Session = Depends(get_db)
):
    existing_patient = db.query(Patient).filter(Patient.id == patId).first()

    if not existing_patient:
        raise HTTPException(
            status_code=404,
            detail="Patient not found"
        )

    db.delete(existing_patient)
    db.commit()

    return {"message": "Patient deleted successfully"}